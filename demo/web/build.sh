#!/usr/bin/env bash
# Build the clickable, backend-free web demo of the family app into demo/web/dist.
#
#   demo/web/build.sh
#
# 1. Exports apps/family for web with the API pointed at a placeholder origin.
# 2. Copies the export to demo/web/dist.
# 3. Writes fixtures.js from fixtures.json and copies mock-api.js next to it.
# 4. Rewrites index.html: relative asset paths, the demo banner, and the two demo scripts
#    loaded before the app bundle, so the mock fetch is in place before the app starts.
#
# The result is static files only. Serve dist/ from any path, e.g.
#   npx serve demo/web/dist   or   python3 -m http.server -d demo/web/dist
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
DIST="$HERE/dist"
API_URL="https://demo.obrigada.invalid"

if [ -f /home/claude/npm-env.sh ]; then
  # shellcheck disable=SC1091
  source /home/claude/npm-env.sh
fi

echo "› Exporting the family app for web (API_URL=$API_URL)"
# --clear: Metro caches the inlined EXPO_PUBLIC_* values, so a stale cache would keep an
# old API URL and the mock would never see the app's requests.
(cd "$ROOT" && EXPO_PUBLIC_API_URL="$API_URL" pnpm --filter @obrigada/family export:web --clear)

echo "› Copying the export to $DIST"
rm -rf "$DIST"
cp -R "$ROOT/apps/family/dist" "$DIST"
rm -f "$DIST/metadata.json"

echo "› Writing fixtures.js and mock-api.js"
node -e '
  const fs = require("fs");
  const fixtures = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
  const js = "/* Generated by demo/web/build.sh from fixtures.json. Do not edit. */\n" +
    "window.__OBRIGADA_FIXTURES__ = " + JSON.stringify(fixtures) + ";\n";
  fs.writeFileSync(process.argv[2], js);
' "$HERE/fixtures.json" "$DIST/fixtures.js"
cp "$HERE/mock-api.js" "$DIST/mock-api.js"

echo "› Rewriting index.html"
node - "$DIST/index.html" "$API_URL" <<'NODE'
const fs = require('fs');
const [file, apiUrl] = process.argv.slice(-2);
let html = fs.readFileSync(file, 'utf8');

// The bundle must actually point at the placeholder origin, or the mock catches nothing.
const bundles = [...html.matchAll(/src="\/?(_expo\/[^"]+\.js)"/g)].map((m) => m[1]);
if (bundles.length === 0) throw new Error('No app bundle found in index.html');
for (const b of bundles) {
  const js = fs.readFileSync(require('path').join(require('path').dirname(file), b), 'utf8');
  if (!js.includes(apiUrl)) throw new Error(`${b} does not use ${apiUrl}; rerun with a clean cache`);
}

// Relative paths: the demo may be served from any sub-path.
html = html.replace(/(src|href)="\/(?!\/)/g, '$1="./');

html = html.replace('<title>family</title>', '<title>Obrigada family app demo</title>');

const style = `
    <style id="demo-style">
      body { margin: 0; display: flex; flex-direction: column; background: #f8f8fa; }
      #root { flex: 1 1 auto; min-height: 0; height: auto; }
      #demo-banner {
        flex: 0 0 auto; padding: 6px 16px; text-align: center;
        font: 500 12px/1.35 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
        color: #5d5d67; background: #ececf1; border-bottom: 1px solid #e4e4ea;
      }
      #demo-toast {
        position: fixed; left: 50%; bottom: 112px; z-index: 2147483647;
        transform: translate(-50%, 8px); opacity: 0; pointer-events: none;
        max-width: calc(100% - 32px); box-sizing: border-box; padding: 10px 16px;
        border-radius: 999px; background: #1d1d23; color: #fff; text-align: center;
        font: 500 13px/1.35 -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
        box-shadow: 0 6px 24px rgba(0,0,0,0.18); transition: opacity .2s, transform .2s;
      }
      #demo-toast.show { opacity: 1; transform: translate(-50%, 0); }
    </style>`;
html = html.replace('</head>', `${style}\n  </head>`);

const banner =
  '<div id="demo-banner" role="note">Demo with recorded and sample data. No live backend.</div>';
html = html.replace('<div id="root"></div>', `${banner}\n    <div id="root"></div>`);

// The demo scripts run first (no defer), before the deferred app bundle.
const scripts = '<script src="./fixtures.js"></script>\n  <script src="./mock-api.js"></script>\n  ';
html = html.replace(/<script src="\.\/_expo\//, (m) => scripts + m);

fs.writeFileSync(file, html);
NODE

COUNT=$(find "$DIST" -type f | wc -l | tr -d ' ')
SIZE=$(du -sh "$DIST" | cut -f1)
echo "✓ Built $DIST ($COUNT files, $SIZE)"
